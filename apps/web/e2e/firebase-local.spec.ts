import {test,expect} from '@playwright/test';
test('local Firebase registration, email verification, workspace and logout',async({page,request},info)=>{
 test.skip(process.env.E2E_FIREBASE_EMULATOR!=='1','Requires an explicitly configured local emulator and API.');
 const config=await request.get('/api/auth/firebase/config');
 expect((await config.json()).config.projectId).toBe('demo-aegis');
 const email=`browser-${info.project.name}-${Date.now()}@example.test`,password='Local-Browser-Password-123!';
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/console');
 const panel=page.getByRole('region',{name:'Firebase identity'});
 await panel.getByLabel('Firebase action').selectOption('create');
 await panel.getByLabel('New AEGIS recovery password · minimum 12 characters').fill(password);
 await panel.getByText('Use Firebase email and password',{exact:true}).click();
 await panel.getByLabel('Firebase email',{exact:true}).fill(email);
 await panel.getByLabel('Firebase password',{exact:true}).fill(password);
 await panel.getByRole('button',{name:'Continue with email',exact:true}).click();
 await expect(panel.getByRole('alert')).toContainText('Verification email sent');
 const oob=await request.get('http://127.0.0.1:9099/emulator/v1/projects/demo-aegis/oobCodes');
 const code=(await oob.json()).oobCodes.find((c:any)=>c.email===email&&c.requestType==='VERIFY_EMAIL').oobCode;
 const verified=await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:update?key=demo-key',{data:{oobCode:code}});
 expect(verified.ok()).toBeTruthy();
 await panel.getByLabel('New AEGIS recovery password · minimum 12 characters').fill(password);
 await panel.getByLabel('Firebase password',{exact:true}).fill(password);
 await panel.getByRole('button',{name:'Continue with email',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Create your company workspace.'})).toBeVisible();
 await page.getByLabel('Company name').fill('Controlled browser workspace');
 await page.getByRole('button',{name:'Create workspace',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your security, in focus.'})).toBeVisible();
 await page.screenshot({path:info.outputPath('workspace.png'),fullPage:true});
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in →',exact:true})).toBeVisible();
 expect(errors).toEqual([]);
});
